#1. Write a program to demonstrate conditional statements using if if-else and if-elif-else.

# if statement
age = 20
if age >= 18:
    print("Adult")

# if-else statement
num = 5
if num > 0:
    print("Positive")
else:
    print("Negative")

# if-elif-else statement
marks = 70
if marks >= 80:
    print("Grade A")
elif marks >= 50:
    print("Grade B")
else:
    print("Grade C")
