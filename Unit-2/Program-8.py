#WAP to explain mutable and immutable object in python.
#1.IMMUTABLE OBJECT (integer, strings, & tuples)
name = "Elizabeth"
print("Name is string : ", name)

#2. MUTABLE OBJECT(lists, dictionaries, and sets)
num = [1, 2, 3]
print("List of  numbers : ", num)

# Changing the first item directly works!
num[0] = 99
print("Updated list : ", num)
